#!/usr/bin/env python3
"""Enhance existing product photos without redrawing, cropping or overwriting originals.
Requires Pillow; outputs WebP display sizes and a source-hash audit manifest.
"""
from pathlib import Path
from html.parser import HTMLParser
from concurrent.futures import ThreadPoolExecutor
import hashlib, json, re
from PIL import Image, ImageFilter, ImageOps
ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'img/product/enhanced-20261115'
WIDTHS = (300, 600, 1024, 1536, 2048, 3840)

def read(file):
    return json.loads((ROOT / file).read_text())

class Pictures(HTMLParser):
    def __init__(self):
        super().__init__(); self.paths = set()
    def handle_starttag(self, tag, attrs):
        a = dict(attrs)
        if tag == 'img' and a.get('src', '').startswith('img/product/'):
            self.paths.add(a['src'].split('?')[0])
        if 'single-product-slide' in a.get('class', '').split():
            match = re.search(r'url\((.*?)\)', a.get('style', ''))
            if match:
                self.paths.add(match[1].strip('\"\''))

def inventory():
    old = read('catalog/product-image-variants.json')
    masters, aliases = {}, {}
    for primary, versions in old.items():
        # New catalog products have actual 1024px originals; the older products'
        # 1024px files are prior resizes and must never become the new source.
        source = versions[-1]['src'] if '/clear-20261110/' not in versions[-1]['src'] else primary
        masters[source] = source
        for key in [primary, *[v['src'] for v in versions]]:
            aliases[key] = source
    parser = Pictures()
    for page in ROOT.glob('*.html'):
        parser.feed(page.read_text())
    for file in sorted(parser.paths):
        if file in aliases or not (ROOT / file).is_file():
            continue
        masters[file] = file; aliases[file] = file
    return old, masters, aliases

def enhance(source):
    raw = (ROOT / source).read_bytes()
    digest = hashlib.sha256(raw).hexdigest()
    with Image.open(ROOT / source) as original:
        image = ImageOps.exif_transpose(original).convert('RGBA' if 'A' in original.getbands() else 'RGB')
    size = image.size
    # Conservative edge sharpening, without colour/shape/lettering changes.
    image = image.filter(ImageFilter.UnsharpMask(radius=.65, percent=65, threshold=3))
    name = re.sub(r'[^a-z0-9]+', '-', Path(source).stem.lower()).strip('-') + '-' + digest[:10]
    versions = []
    for width in WIDTHS:
        height = max(1, round(size[1] * width / size[0]))
        resized = image.resize((width, height), Image.Resampling.LANCZOS)
        if width > size[0]:
            resized = resized.filter(ImageFilter.UnsharpMask(radius=.5, percent=25, threshold=3))
        target = OUT / (name + '-' + str(width) + '.webp')
        resized.save(target, 'WEBP', quality=95, method=4, exact=True)
        versions.append({'src': target.relative_to(ROOT).as_posix(), 'width': width})
    return source, {'source': source, 'sha256': digest, 'original_width': size[0], 'original_height': size[1], 'variants': versions}

def main():
    old, masters, aliases = inventory()
    OUT.mkdir(parents=True, exist_ok=True)
    groups = {}
    with ThreadPoolExecutor(max_workers=4) as pool:
        for index, (source, group) in enumerate(pool.map(enhance, sorted(masters)), 1):
            groups[source] = group
            if index % 20 == 0:
                print('Enhanced', index, 'of', len(masters), 'pictures', flush=True)
    images = {alias: groups[source]['variants'] for alias, source in sorted(aliases.items())}
    manifest = {'method': 'Conservative sharpening and Lanczos resizing; no generated detail or original replacement.', 'catalog_primary_count': len(old), 'groups': list(groups.values()), 'images': images}
    (ROOT / 'catalog/product-image-enhancements.json').write_text(json.dumps(manifest, indent=2) + '\n')
    runtime = (ROOT / 'scripts/product-images-runtime.txt').read_text()
    combined = dict(old); combined.update(images)
    (ROOT / 'js/product-images.js').write_text('/* Existing-photo responsive variants. Generated by scripts/enhance-product-images.py. */\n(function(root){\n\'use strict\';\nconst variants=' + json.dumps(combined, separators=(',', ':')) + ';\n' + runtime + '\n})(window);\n')
    print('Complete:', len(old), 'catalog products,', len(groups), 'distinct product pictures,', len(images), 'mapped paths.', flush=True)
if __name__ == '__main__':
    main()
